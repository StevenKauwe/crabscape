use bevy_egui::egui::Color32;
use gridcraft_ui_egui::theme::Tokens;
fn rgb(r: u8, g: u8, b: u8) -> Color32 {
    Color32::from_rgb(r, g, b)
}

/// Original "royal" palette: midnight chrome, dark cells, gold selection.
pub(super) fn royal(paper: bool) -> Tokens {
    let mut t = Tokens {
        dark: true,
        window: rgb(0x0E, 0x12, 0x20),
        ribbon: rgb(0x12, 0x18, 0x28),
        ribbon_border: rgb(0x23, 0x2C, 0x42),
        text: rgb(0xE8, 0xEC, 0xF6),
        text_dim: rgb(0x8C, 0x96, 0xB2),
        text_disabled: rgb(0x55, 0x5E, 0x78),
        accent: rgb(0xF2, 0xC1, 0x4E),
        accent_dark: rgb(0xD9, 0xA6, 0x2E),
        accent_soft: rgb(0x3A, 0x32, 0x18),
        hover: rgb(0x1C, 0x24, 0x38),
        pressed: rgb(0x25, 0x30, 0x49),
        separator: rgb(0x23, 0x2C, 0x42),
        grid_bg: rgb(0x0F, 0x14, 0x22),
        gridline: rgb(0x1F, 0x27, 0x3A),
        header_bg: rgb(0x13, 0x19, 0x2A),
        header_text: rgb(0x8C, 0x96, 0xB2),
        header_line: rgb(0x26, 0x2F, 0x46),
        header_sel_bg: rgb(0x33, 0x2B, 0x12),
        header_sel_text: rgb(0xF2, 0xC1, 0x4E),
        header_all_bg: rgb(0x33, 0x2B, 0x12),
        sel_fill: Color32::from_rgba_unmultiplied(0xF2, 0xC1, 0x4E, 0x26),
        sel_border: rgb(0xF2, 0xC1, 0x4E),
        input_bg: rgb(0x0B, 0x0F, 0x1A),
        input_border: rgb(0x2A, 0x34, 0x50),
        tab_bar: rgb(0x0E, 0x12, 0x20),
        tab_active: rgb(0x1A, 0x21, 0x33),
        status_bar: rgb(0x0E, 0x12, 0x20),
        cell_text: rgb(0xDC, 0xE3, 0xF2),
        menu_bg: rgb(0x14, 0x1B, 0x2C),
        shadow: Color32::from_black_alpha(150),
        danger: rgb(0xFF, 0x6B, 0x6B),
    };
    if paper {
        t.grid_bg = rgb(0xFB, 0xFA, 0xF6);
        t.gridline = rgb(0xE2, 0xE1, 0xDC);
        t.cell_text = rgb(0x1A, 0x1D, 0x26);
        t.sel_fill = Color32::from_rgba_unmultiplied(0xD9, 0xA6, 0x2E, 0x2A);
        t.sel_border = rgb(0xC8, 0x8F, 0x12);
    }
    t
}
