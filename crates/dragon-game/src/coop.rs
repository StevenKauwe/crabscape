//! Static shared-sky runtime. No socket, save, wall clock or new wire topics.
//! `receive` accepts ONLY messages admitted by dragon-peer's version/channel/sequence
//! checks. Peer/rider bindings are provided by the authenticated transport's slot
//! admission, never inferred from an action's `r`. A disconnect invalidates binding.
//! Presence supplies casts (including Guardian healing); retired riders stay retired.
use crate::{
    authority::{Authority, Candidate},
    damage, enemies,
    flight::{Input, Viewport},
    game::Game,
    network_actions::{self as actions, Ghost, Sender},
    network_world::{self as world, GuestWorld, Mirror},
    objectives, projectiles,
};
use serde_json::{Value, json};
use std::collections::BTreeMap;

#[derive(Clone, Debug, PartialEq)]
pub struct Outbound {
    pub topic: &'static str,
    pub data: Value,
}
#[derive(Clone, Debug)]
struct Binding {
    rider: usize,
    daddio: bool,
}
#[derive(Clone, Debug)]
pub(crate) enum GameEvent {
    Hit(projectiles::Event),
    Calm(u64),
    Defeat {
        id: u64,
        kind: enemies::Kind,
        at: [f64; 2],
        calmed: bool,
        by: usize,
    },
    Handoff,
}
#[derive(Default)]
pub(crate) struct Runtime {
    pub enabled: bool,
    pub rider: usize,
    pub active_others: usize,
    pub others: Vec<objectives::Rider>,
    pub aims: Vec<objectives::Rider>,
    pub destinations: BTreeMap<u64, [f64; 2]>,
    pub events: Vec<GameEvent>,
    pub sky: f64,
    pub remote_by: Option<usize>,
    pub retired: bool,
}
/// One local player with host-owned shared enemies/objective. The Game's profile,
/// gems, carried/banked rewards and player never come from another device.
pub struct Session {
    pub game: Game,
    pub peer: String,
    pub rider: usize,
    pub ghosts: BTreeMap<String, Ghost>,
    pub presentation: Vec<actions::PresenceEffect>,
    world: GuestWorld,
    peers: BTreeMap<String, Binding>,
    outbound: Vec<Outbound>,
    ghost_order: Vec<String>,
    paused: bool,
    now: f64,
    frame_time: f64,
    world_sent: f64,
    presence_sent: f64,
    last_presence: Option<Value>,
}
impl Session {
    pub fn validate_identity(
        peer: &str,
        rider: usize,
        run: &str,
        authority: &Authority,
    ) -> Result<(), &'static str> {
        if peer.is_empty()
            || rider >= 6
            || (run.is_empty() && !authority.guest)
            || run.encode_utf16().count() > 12
            || authority.host_rider >= 6
            || (authority.guest && authority.host_peer.is_none())
        {
            return Err("invalid shared sky identity");
        }
        Ok(())
    }
    /// Join an existing run using its advertised host/epoch, or pass a host Authority.
    /// Run IDs are generated by the outer application, never by a hidden RNG/clock.
    pub fn new(
        mut game: Game,
        peer: String,
        rider: usize,
        run: String,
        authority: Authority,
    ) -> Result<Self, &'static str> {
        Self::validate_identity(&peer, rider, &run, &authority)?;
        game.net.enabled = true;
        game.net.rider = rider;
        game.net.sky = 1.;
        game.mission.guest = authority.guest;
        let mut world = GuestWorld::new(
            game.definition.id.clone(),
            game.definition.waves.len(),
            authority,
        );
        world.run = run;
        world.mission = game.mission.clone();
        Ok(Self {
            game,
            peer,
            rider,
            ghosts: BTreeMap::new(),
            presentation: vec![],
            world,
            peers: BTreeMap::new(),
            outbound: vec![],
            ghost_order: vec![],
            paused: false,
            now: 0.,
            frame_time: 0.,
            world_sent: f64::NEG_INFINITY,
            presence_sent: f64::NEG_INFINITY,
            last_presence: None,
        })
    }
    pub fn authority(&self) -> &Authority {
        &self.world.authority
    }
    pub fn run(&self) -> &str {
        &self.world.run
    }
    pub fn bind_peer(
        &mut self,
        peer: String,
        rider: usize,
        daddio: bool,
    ) -> Result<(), &'static str> {
        if peer.is_empty()
            || peer == self.peer
            || rider >= 6
            || rider == self.rider
            || self
                .peers
                .iter()
                .any(|(p, b)| p != &peer && b.rider == rider)
            || (!self.peers.contains_key(&peer) && self.peers.len() >= 5)
        {
            return Err("invalid peer slot");
        }
        if self.peers.get(&peer).is_some_and(|b| b.rider != rider) {
            self.ghosts.remove(&peer);
        }
        self.peers.insert(peer, Binding { rider, daddio });
        Ok(())
    }
    pub fn disconnect(&mut self, peer: &str) {
        self.ghost_order.retain(|p| p != peer);
        self.peers.remove(peer);
        self.ghosts.remove(peer);
        self.refresh_context();
    }
    pub fn drain_outbound(&mut self) -> Vec<Outbound> {
        std::mem::take(&mut self.outbound)
    }
    fn view(&self) -> world::Viewport {
        let v = self.game.view;
        world::Viewport {
            width: v.width,
            top: v.top_limit,
            ground: v.ground_y,
            scale: v.scale,
        }
    }
    fn envelope(&self) -> Value {
        json!({"r":self.rider,"mid":self.game.definition.id,"run":self.world.run,"epoch":self.world.authority.epoch})
    }
    fn emit(&mut self, topic: &'static str, data: Value) {
        self.outbound.push(Outbound { topic, data });
    }
    // Move arrays across the codec boundary; no cloned enemy simulation each frame.
    fn export_world(&mut self) {
        self.world.mission = self.game.mission.clone();
        self.world.objective = self.game.objective.take();
        self.world.next_uid = self.game.uid;
        self.world.enemies = std::mem::take(&mut self.game.enemies)
            .into_iter()
            .map(|enemy| {
                let destination = self
                    .game
                    .net
                    .destinations
                    .get(&enemy.target.id)
                    .copied()
                    .unwrap_or([enemy.target.x, enemy.target.y]);
                Mirror { enemy, destination }
            })
            .collect();
        self.world.hazards = std::mem::take(&mut self.game.hazards)
            .into_iter()
            .map(|h| world::NetworkHazard {
                uid: h.uid,
                spin: h.spin,
                hazard: enemies::Hazard {
                    kind: serde_json::from_value(json!(h.kind)).expect("known hazard"),
                    position: [h.x, h.y],
                    velocity: [h.vx, h.vy],
                    gravity: h.gravity,
                    radius: h.r,
                    life: h.life,
                    warn: h.warn,
                },
            })
            .collect();
        self.world.strikes = std::mem::take(&mut self.game.strikes)
            .into_iter()
            .map(|s| world::Strike {
                uid: s.uid,
                x: s.x,
                warn: s.warn,
                bolt: s.bolt,
                y0: s.y0,
                hit: s.hit,
            })
            .collect();
        self.world.used_hazards = self.game.used.hazards.iter().copied().collect();
        self.world.used_strikes = self.game.used.strikes.iter().copied().collect();
        self.world.fail_why = self.game.fail_reason.clone().unwrap_or_default();
    }
    fn import_world(&mut self) {
        self.game.mission = self.world.mission.clone();
        self.game.mission.guest = self.world.authority.guest;
        self.game.objective = self.world.objective.take();
        self.game.uid = self.game.uid.max(self.world.next_uid);
        self.game.net.destinations.clear();
        self.game.enemies = std::mem::take(&mut self.world.enemies)
            .into_iter()
            .map(|m| {
                self.game
                    .net
                    .destinations
                    .insert(m.enemy.target.id, m.destination);
                m.enemy
            })
            .collect();
        self.game.hazards = std::mem::take(&mut self.world.hazards)
            .into_iter()
            .map(|h| damage::Hazard {
                uid: h.uid,
                x: h.hazard.position[0],
                y: h.hazard.position[1],
                vx: h.hazard.velocity[0],
                vy: h.hazard.velocity[1],
                gravity: h.hazard.gravity,
                r: h.hazard.radius,
                life: h.hazard.life,
                warn: h.hazard.warn,
                spin: h.spin,
                kind: serde_json::to_value(h.hazard.kind)
                    .unwrap()
                    .as_str()
                    .unwrap()
                    .into(),
            })
            .collect();
        self.game.strikes = std::mem::take(&mut self.world.strikes)
            .into_iter()
            .map(|s| damage::Strike {
                uid: s.uid,
                x: s.x,
                warn: s.warn,
                bolt: s.bolt,
                y0: s.y0,
                hit: s.hit,
            })
            .collect();
    }
    /// Already replay-filtered message from the authenticated transport connection.
    /// Returns false for unknown peer, spoofed rider, stale run/epoch, invalid topic.
    pub fn receive(&mut self, peer: &str, topic: &str, data: &Value, now: f64) -> bool {
        if !now.is_finite() || now < self.now || !data.is_object() {
            return false;
        }
        let Some(binding) = self.peers.get(peer).cloned() else {
            return false;
        };
        if data["r"].as_u64() != Some(binding.rider as u64) {
            return false;
        }
        self.now = now;
        let sender = Some(Sender {
            peer,
            rider: binding.rider,
            daddio: binding.daddio,
        });
        match topic {
            "presence" => {
                let mut ghost = self.ghosts.remove(peer);
                let ctx = actions::PresenceContext {
                    local_rider: self.rider,
                    playing: !self.paused && self.game.result.is_none(),
                    local_mission: Some(&self.game.definition.id),
                    local_host: !self.world.authority.guest,
                    objective_carrier: self
                        .game
                        .objective
                        .as_ref()
                        .and_then(|o| usize::try_from(o.carrier).ok()),
                    player: [self.game.player.x, self.game.player.y],
                    player_out: self.game.player.out,
                    scale: self.game.view.scale,
                };
                let effects =
                    actions::ingest_presence(&mut ghost, sender, data, ctx, Game::known_mission);
                if let Some(g) = ghost {
                    if !self.ghost_order.iter().any(|p| p == peer) {
                        self.ghost_order.push(peer.into());
                    }
                    self.ghosts.insert(peer.into(), g);
                }
                let Some(effects) = effects else {
                    return false;
                };
                for e in effects {
                    match e {
                        actions::PresenceEffect::ApplyTeamSpell(spell) => {
                            self.game.apply_team_spell(spell)
                        }
                        actions::PresenceEffect::DropPieceBonk => self.game.drop_network_piece(),
                        actions::PresenceEffect::GuardianHeal => {
                            self.game.player.hearts = self
                                .game
                                .max_hearts()
                                .min(self.game.player.hearts.saturating_add(1));
                            self.game.player.shield = self.game.player.shield.max(2.5);
                        }
                        _ => self.presentation.push(e),
                    }
                }
                self.reconcile(false);
                self.refresh_context();
                self.flush_game_events();
                true
            }
            "world" => {
                self.export_world();
                let v = self.view();
                let mut rng = self.game.rng;
                let result = self
                    .world
                    .receive(data, peer, v, self.frame_time, &mut |kind, at| {
                        self.game.make_mirror(kind, at, &mut || rng.next_unit())
                    });
                self.game.rng = rng;
                self.import_world();
                let Some(events) = result else {
                    return false;
                };
                for e in events {
                    match e {
                        world::Event::Bank(_) => self.game.bank_network_gems(),
                        world::Event::Sound(cue) => {
                            use crate::game::sound::{self, Event as S};
                            sound::push(
                                &mut self.game.sound_events,
                                match cue {
                                    world::Sound::Wave => S::Wave,
                                    world::Sound::Wrong => S::Wrong,
                                    world::Sound::Win => S::Win,
                                },
                            );
                        }
                        world::Event::FailureCaption(s) => self.game.fail_reason = Some(s),
                        _ => {}
                    }
                }
                true
            }
            "hit" => {
                let Some(hit) = actions::remote_hit(&self.world, &self.game.enemies, sender, data)
                else {
                    return false;
                };
                self.game.apply_network_hit(hit);
                self.flush_game_events();
                true
            }
            "defeat" => {
                let Some(effects) =
                    actions::remote_defeat(&self.world, sender, data, self.rider, self.view())
                else {
                    return false;
                };
                self.game.apply_network_defeat(effects);
                true
            }
            "handoff" => {
                let ghosts: Vec<_> = self
                    .ghost_order
                    .iter()
                    .filter_map(|p| self.ghosts.get(p))
                    .cloned()
                    .collect();
                let Some(action) = actions::handoff(
                    &self.world,
                    sender,
                    data,
                    &ghosts,
                    self.rider,
                    self.game.player.out,
                ) else {
                    return false;
                };
                match action {
                    actions::Handoff::BecomeHost => self.takeover(actions::TakeoverReason::Handoff),
                    actions::Handoff::Follow { rider, peer } => {
                        self.world.authority.host_rider = rider;
                        self.world.authority.host_peer = peer;
                        self.world.last_world = self.frame_time;
                    }
                }
                true
            }
            _ => false,
        }
    }
    fn refresh_context(&mut self) {
        let v = self.view();
        self.game.net.active_others = self
            .ghosts
            .values()
            .filter(|g| {
                g.mission.as_deref() == Some(&self.game.definition.id)
                    && matches!(g.status.as_str(), "play" | "pause")
                    && !g.out
            })
            .count();
        self.game.net.others = self
            .ghost_order
            .iter()
            .filter_map(|p| self.ghosts.get(p))
            .filter(|g| {
                g.mission.as_deref() == Some(&self.game.definition.id)
                    && matches!(g.status.as_str(), "play" | "pause")
                    && !g.out
            })
            .filter(|g| g.position.is_some())
            .map(|g| {
                let [x, y] = g.position.unwrap_or([
                    g.target[0] * v.width,
                    v.top + g.target[1] * (v.ground - v.top),
                ]);
                objectives::Rider {
                    id: g.rider as i32,
                    x,
                    y,
                }
            })
            .collect();
        self.game.net.aims = self
            .ghost_order
            .iter()
            .filter_map(|p| self.ghosts.get(p))
            .filter(|g| {
                g.mission.as_deref() == Some(&self.game.definition.id)
                    && g.status == "play"
                    && !g.out
                    && g.position.is_some()
            })
            .map(|g| {
                let [x, y] = g.position.unwrap();
                objectives::Rider {
                    id: g.rider as i32,
                    x,
                    y,
                }
            })
            .collect();
        self.game.net.sky = 1.
            + 0.6
                * self
                    .ghosts
                    .values()
                    .filter(|g| {
                        g.mission.as_deref() == Some(&self.game.definition.id)
                            && g.status == "play"
                            && self.peers.get(&g.peer).is_some_and(|b| !b.daddio)
                    })
                    .count() as f64;
    }
    fn reconcile(&mut self, timed_out: bool) {
        let mut candidates: Vec<_> = self
            .ghosts
            .values()
            .filter(|g| {
                g.mission.as_deref() == Some(&self.game.definition.id)
                    && g.run.as_deref() == Some(&self.world.run)
                    && !g.out
                    && matches!(g.status.as_str(), "play" | "pause")
            })
            .map(|g| Candidate {
                peer: g.peer.clone(),
                rider: g.rider,
                host: g.host,
                epoch: g.epoch,
                paused: g.status == "pause",
            })
            .collect();
        if !self.game.player.out {
            candidates.push(Candidate {
                peer: self.peer.clone(),
                rider: self.rider,
                host: !self.world.authority.guest,
                epoch: self.world.authority.epoch,
                paused: self.paused,
            });
        }
        let result = self
            .world
            .authority
            .reconcile(&self.peer, &candidates, timed_out);
        if result.refresh_world_time {
            self.world.last_world = self.frame_time;
        }
        self.game.mission.guest = self.world.authority.guest;
        if result.become_host {
            self.takeover(actions::TakeoverReason::Lost);
        }
        if result.reset_presence {
            self.last_presence = None;
            self.presence_sent = f64::NEG_INFINITY;
        }
    }
    fn takeover(&mut self, why: actions::TakeoverReason) {
        self.export_world();
        let mut rng = self.game.rng;
        if let Some(t) = actions::become_host(&mut self.world, why, &mut || rng.next_unit()) {
            self.world.enemies = t
                .enemies
                .into_iter()
                .map(|enemy| Mirror {
                    destination: [enemy.target.x, enemy.target.y],
                    enemy,
                })
                .collect();
        }
        self.game.rng = rng;
        self.import_world();
        self.world.authority.host_rider = self.rider;
        self.last_presence = None;
        self.presence_sent = f64::NEG_INFINITY;
        self.world_sent = f64::NEG_INFINITY;
    }
    fn flush_game_events(&mut self) {
        for e in std::mem::take(&mut self.game.net.events) {
            let mut packet = self.envelope();
            match e {
                GameEvent::Hit(projectiles::Event::GuestHit {
                    id,
                    dmg,
                    kind,
                    slow,
                    stun,
                    mega,
                    mark,
                    crack,
                }) => {
                    packet["uid"] = json!(id);
                    packet["dmg"] = json!(dmg);
                    packet["kind"] = json!(kind);
                    packet["slow"] = json!(slow);
                    packet["stun"] = json!(stun);
                    packet["mega"] = json!(u8::from(mega));
                    packet["mk"] = json!(u8::from(mark));
                    packet["cr"] = json!(u8::from(crack));
                    self.emit("hit", packet);
                }
                GameEvent::Calm(id) => {
                    packet["uid"] = json!(id);
                    packet["calm"] = json!(1);
                    self.emit("hit", packet);
                }
                GameEvent::Defeat {
                    id,
                    kind,
                    at,
                    calmed,
                    by,
                } => {
                    packet["uid"] = json!(id);
                    packet["type"] = json!(kind);
                    packet["x"] = json!(at[0] / self.game.view.width);
                    packet["y"] = json!(
                        (at[1] - self.game.view.top_limit)
                            / (self.game.view.ground_y - self.game.view.top_limit).max(1.)
                    );
                    packet["calmed"] = json!(calmed);
                    packet["by"] = json!(by);
                    self.emit("defeat", packet);
                }
                GameEvent::Handoff => {
                    self.emit("handoff", packet);
                    if let Some(next) = self
                        .ghosts
                        .values()
                        .filter(|g| {
                            !g.out
                                && g.mission.as_deref() == Some(&self.game.definition.id)
                                && matches!(g.status.as_str(), "play" | "pause")
                        })
                        .min_by_key(|g| g.rider)
                    {
                        self.world.authority.guest = true;
                        self.world.authority.host_peer = Some(next.peer.clone());
                        self.world.authority.host_rider = next.rider;
                        self.world.last_world = self.frame_time;
                        self.game.mission.guest = true;
                    }
                }
                GameEvent::Hit(_) => {}
            }
        }
    }
    /// `now` is monotonic transport time in seconds, independent of paused simulation.
    /// Paused hosts keep presence; no update(0) masquerading as pause.
    pub fn step(
        &mut self,
        dt: f64,
        input: Input,
        view: Viewport,
        now: f64,
        paused: bool,
    ) -> Result<(), &'static str> {
        if !now.is_finite() || now < self.now || !dt.is_finite() {
            return Err("invalid session time");
        }
        self.now = now;
        let frame_dt = if self.game.hit_stop > 0. {
            0.
        } else {
            dt.clamp(0., 0.05)
        };
        self.frame_time += frame_dt;
        if paused && self.game.hit_stop > 0. {
            self.game.hit_stop -= dt.clamp(0., 0.05);
        }
        self.paused = paused;
        self.game.resize_network(view)?;
        self.refresh_context();
        self.reconcile(false);
        if !paused {
            let world = &mut self.world;
            let ghosts = &self.ghosts;
            let mine = &self.peer;
            let rider = self.rider;
            let clock = self.frame_time;
            let mut reset = false;
            self.game.step_network(dt, input, view, &mut |game, draw| {
                if !world.authority.guest
                    || game.mission.done
                    || game.mission.fail_t > 0.
                    || clock - world.last_world <= 3.5
                {
                    return false;
                }
                let mut candidates: Vec<_> = ghosts
                    .values()
                    .filter(|g| {
                        g.mission.as_deref() == Some(&game.definition.id)
                            && g.run.as_deref() == Some(&world.run)
                            && !g.out
                            && matches!(g.status.as_str(), "play" | "pause")
                    })
                    .map(|g| Candidate {
                        peer: g.peer.clone(),
                        rider: g.rider,
                        host: g.host,
                        epoch: g.epoch,
                        paused: g.status == "pause",
                    })
                    .collect();
                if !game.player.out {
                    candidates.push(Candidate {
                        peer: mine.clone(),
                        rider,
                        host: false,
                        epoch: world.authority.epoch,
                        paused: false,
                    });
                }
                let election = world.authority.reconcile(mine, &candidates, true);
                if election.refresh_world_time {
                    world.last_world = clock;
                }
                reset = election.reset_presence;
                if election.become_host {
                    takeover_game(game, world, actions::TakeoverReason::Lost, draw);
                    world.authority.host_rider = rider;
                    return true;
                }
                game.mission.guest = world.authority.guest;
                false
            })?;
            if reset {
                self.last_presence = None;
                self.presence_sent = f64::NEG_INFINITY;
                self.world_sent = f64::NEG_INFINITY;
            }
        }
        // Source updateGhosts runs after update, so this position affects the next
        // frame's aim/objective and any presence callbacks delivered afterward.
        let v = self.view();
        let k = (frame_dt * 10.).min(1.);
        for g in self.ghosts.values_mut() {
            let target = [
                g.target[0] * v.width,
                v.top + g.target[1] * (v.ground - v.top),
            ];
            let p = g.position.get_or_insert(target);
            p[0] += (target[0] - p[0]) * k;
            p[1] += (target[1] - p[1]) * k;
        }
        self.flush_game_events();
        if !paused
            && !self.world.authority.guest
            && !self.peers.is_empty()
            && self.frame_time - self.world_sent >= 0.066
        {
            self.export_world();
            let packet = world::encode_world(&self.world, self.rider, self.view());
            self.import_world();
            self.emit("world", packet);
            self.world_sent = self.frame_time;
        }
        if now - self.presence_sent >= 0.08 {
            let p = &self.game.player;
            let m = &self.game.mission;
            let guest = self.world.authority.guest;
            let boss = self
                .game
                .enemies
                .iter()
                .find(|e| e.target.boss && !e.target.dead);
            let round = |v: f64| (v * 1000.).round() / 1000.;
            let packet = json!({"r":self.rider,"s":if self.game.result.is_some(){"results"}else if paused{"pause"}else{"play"},"f":p.facing,"rd":u8::from(self.game.network_riding()),"sh":u8::from(p.shield>0.),"o":u8::from(p.out),"h":p.hearts,"x":round((p.x/view.width).clamp(0.,1.)),"y":round(((p.y-view.top_limit)/(view.ground_y-view.top_limit).max(1.)).clamp(0.,1.)),"cs":[self.game.cast_count,self.game.last_cast],"ms":[self.game.definition.id,m.wave,if guest{0}else{m.kills},if guest{0.}else{boss.map_or(0.,|b|(b.target.max_hp-b.target.hp).max(0.).round())},self.world.run,u8::from(!guest),self.world.authority.epoch]});
            self.presence_sent = now;
            if self.last_presence.as_ref() != Some(&packet) {
                self.last_presence = Some(packet.clone());
                self.emit("presence", packet);
            }
        }
        Ok(())
    }
    /// Explicit leave/mission abandonment, not a new protocol message.
    pub fn handoff(&mut self) {
        if !self.world.authority.guest {
            self.game.net.events.push(GameEvent::Handoff);
            self.flush_game_events();
        }
    }
}

fn takeover_game(
    game: &mut Game,
    world: &mut GuestWorld,
    why: actions::TakeoverReason,
    draw: &mut dyn FnMut() -> f64,
) {
    world.mission = game.mission.clone();
    world.enemies = std::mem::take(&mut game.enemies)
        .into_iter()
        .map(|enemy| Mirror {
            destination: [enemy.target.x, enemy.target.y],
            enemy,
        })
        .collect();
    if let Some(t) = actions::become_host(world, why, &mut || draw()) {
        game.enemies = t.enemies;
    } else {
        game.enemies = std::mem::take(&mut world.enemies)
            .into_iter()
            .map(|m| m.enemy)
            .collect();
    }
    game.mission = world.mission.clone();
    game.mission.guest = world.authority.guest;
    game.net.destinations.clear();
    game.uid = game.uid.max(world.next_uid);
}
